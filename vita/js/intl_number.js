	var plain = null;

	function formatter(locales, options) {
		if (locales === undefined && options === undefined)
			return plain || (plain = new NumberFormat());
		return new NumberFormat(locales, options);
	}

	method(Number.prototype, 'toLocaleString', function toLocaleString() {
		var x = this;

		if (typeof x === 'object' && x instanceof Number)
			x = Number.prototype.valueOf.call(x);
		if (typeof x !== 'number')
			throw new TypeError('Number.prototype.toLocaleString ' +
					    'requires that \'this\' be a Number');
		return formatter(arguments[0], arguments[1]).format(x);
	});
	if (typeof BigInt !== 'undefined') {
		method(BigInt.prototype, 'toLocaleString',
		       function toLocaleString() {
			var x = BigInt.prototype.valueOf.call(this);

			return formatter(arguments[0], arguments[1]).format(x);
		});
	}
