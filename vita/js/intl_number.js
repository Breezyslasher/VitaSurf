	var PR_SLOTS = new WeakMap();

	function prSlots(pr, method) {
		var s = pr !== null && typeof pr === 'object' && PR_SLOTS.get(pr);

		if (!s)
			throw new TypeError('Method Intl.PluralRules.prototype.' +
					    method + ' called on incompatible ' +
					    'receiver');
		return s;
	}

	function PluralRules() {
		var s = {}, o, loc;

		if (!new.target)
			throw new TypeError('Constructor Intl.PluralRules requires ' +
					    '\'new\'');
		var req = C.localeList(arguments[0]), options = arguments[1];

		o = options === undefined ? Object.create(null) : toObject(options);
		getOption(o, 'localeMatcher', ['lookup', 'best fit'], 'best fit');
		s.type = getOption(o, 'type', ['cardinal', 'ordinal'], 'cardinal');
		digitOptions(s, o, 0, 3, 'standard');
		loc = resolveLocale(req, undefined, false, hasPlural);
		s.locale = loc.locale;
		s.tag = loc.tag;
		s.rules = rulesFor(loc.tag, s.type === 'ordinal' ? 'o' : 'c');
		PR_SLOTS.set(this, s);
		return this;
	}

	var prProto = PluralRules.prototype;

	function selectOf(s, v) {
		if (v.nan || v.inf)
			return 'other';
		var r = toDigits(s, { neg: false, d: v.d, q: v.q });

		return category(s.rules, operands(r.int, r.frac, 0));
	}

	method(prProto, 'select', function select(n) {
		var s = prSlots(this, 'select');

		return selectOf(s, fromNumber(Number(n)));
	});

	method(prProto, 'selectRange', function selectRange(a, b) {
		var s = prSlots(this, 'selectRange'), x, y;

		if (a === undefined || b === undefined)
			throw new TypeError('start or end is undefined');
		x = Number(a);
		y = Number(b);
		if (x !== x || y !== y)
			throw new RangeError('Invalid number value: NaN');
		return rangeCategory(rulesFor(s.tag, 'c'),
				     selectOf(s, fromNumber(x)),
				     selectOf(s, fromNumber(y)));
	});

	method(prProto, 'resolvedOptions', function resolvedOptions() {
		var s = prSlots(this, 'resolvedOptions'), r = {}, i;
		var KEYS = ['locale', 'type', 'minimumIntegerDigits',
			'minimumFractionDigits', 'maximumFractionDigits',
			'minimumSignificantDigits', 'maximumSignificantDigits',
			'pluralCategories', 'roundingIncrement', 'roundingMode',
			'roundingPriority', 'trailingZeroDisplay'];

		for (i = 0; i < KEYS.length; i++) {
			var k = KEYS[i], v = s[k];

			if (k === 'pluralCategories')
				v = SPEC_ORDER.filter(function (c) {
					return s.rules.some(function (x) {
						return x[0] === c;
					});
				});
			if (v !== undefined)
				r[k] = v;
		}
		return r;
	});

	Object.defineProperty(prProto, Symbol.toStringTag, {
		configurable: true, value: 'Intl.PluralRules'
	});
	method(PluralRules, 'supportedLocalesOf',
	       function supportedLocalesOf(locales) {
		return supported(locales, arguments[1], hasPlural);
	});
	Object.defineProperty(PluralRules, 'prototype', { writable: false });

	Intl.NumberFormat = NumberFormat;
	Intl.PluralRules = PluralRules;

	var values = Intl.supportedValuesOf;

	Intl.supportedValuesOf = function supportedValuesOf(key) {
		key = String(key);
		if (key === 'currency')
			return index().currencies.slice();
		if (key === 'unit')
			return UNITS.slice().sort();
		if (key === 'numberingSystem')
			return Object.keys(index().ns).sort();
		return values ? values.call(this, key) : [];
	};

